/**
 * Палитра графиков панели.
 *
 * Два ряда на графике - контейнеры стенда: приложение и база. Цвет закреплён
 * за сущностью, а не за порядком: база всегда синяя, даже если приложение
 * отфильтровали и она осталась одна.
 *
 * Ступени под тёмную тему подобраны отдельно, а не осветлены автоматически:
 * на почти чёрном фоне те же светлые тона вываливаются из полосы светлоты и
 * теряют насыщенность. Обе пары прогнаны валидатором палитр - проходят полосу
 * светлоты, порог насыщенности, разделимость при дальтонизме и контраст
 * к поверхности:
 *
 *   светлая (#FAFAF9): ΔE 18.5 при дейтеранопии, 19.2 при обычном зрении
 *   тёмная  (#0C0C0D): ΔE 23.8 при дейтеранопии, 24.8 при обычном зрении
 *
 * Порог - 8; ниже пришлось бы дублировать различие штриховкой.
 */
export interface SeriesColors {
  /** Линия и подпись. */
  line: string
  /** Заливка под линией. Прозрачность даёт пересечению рядов читаемость. */
  fill: string
}

