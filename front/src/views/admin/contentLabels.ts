/**
 * `cta_brief_body` -> «призыв · что написать · текст».
 *
 * Перевод по частям, а не по целому ключу: ключи собираются из одних и тех же
 * кусков, и словарь из тридцати слов покрывает их все, тогда как словарь по
 * целым ключам пришлось бы дополнять при каждой новой строке на сайте.
 */
export function humanizeKey(key: string): string {
  const parts = key.split('_')
  const words = parts.map(p => WORD[p] ?? p)
  return words.join(' · ')
}
